#!/bin/sh
# Apply the built-in management-page binary to one existing Compose service.
set -eu
set -f

fail() { printf '安装失败：%s\n' "$*" >&2; exit 1; }
if [ "$#" -gt 2 ]; then
  fail '用法：sh gpt-monitor-patch/apply.sh docker-compose.yml [sub2api]'
fi
compose_file=docker-compose.yml
service=sub2api
if [ "$#" -ge 1 ]; then compose_file=$1; fi
if [ "$#" -ge 2 ]; then service=$2; fi
case "$service" in ''|*[!a-zA-Z0-9_.-]*) fail '服务名只能包含字母、数字、下划线、点和短横线' ;; esac
[ -f "$compose_file" ] || fail '找不到原 Compose 文件；请在原部署目录执行'
compose_dir=$(CDPATH= cd -- "$(dirname -- "$compose_file")" && pwd -P)
[ "$(pwd -P)" = "$compose_dir" ] || fail '请先进入原 Compose 文件所在目录，再执行安装脚本'
compose_file="$compose_dir/$(basename -- "$compose_file")"
bundle_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)
override_file="$compose_dir/docker-compose.gpt-monitor.yml"
case "$bundle_dir$compose_file" in
  *'
'*) fail '路径不能包含换行符' ;;
esac
[ ! -e "$override_file" ] && [ ! -L "$override_file" ] || fail 'docker-compose.gpt-monitor.yml 已存在；为避免覆盖，已停止安装'
command -v sha256sum >/dev/null 2>&1 || fail '系统缺少 sha256sum'
[ -f "$bundle_dir/SHA256SUMS" ] || fail '安装包缺少 SHA256SUMS'
[ -f "$bundle_dir/UPSTREAM_BASE.txt" ] || fail '安装包缺少 UPSTREAM_BASE.txt'
[ -f "$bundle_dir/bin/linux-amd64/sub2api" ] || fail '安装包缺少 amd64 程序'
[ -f "$bundle_dir/bin/linux-arm64/sub2api" ] || fail '安装包缺少 arm64 程序'
(cd "$bundle_dir" && sha256sum -c SHA256SUMS) || fail '文件校验失败，请重新获取完整安装包'
command -v docker >/dev/null 2>&1 || fail '找不到 docker 命令'
docker compose version >/dev/null 2>&1 || fail '需要 Docker Compose v2（docker compose）'

base_compose() { docker compose -f "$compose_file" "$@"; }
container_id=$(base_compose ps -q "$service") || fail '读取现有 Compose 服务失败'
case "$container_id" in ''|*[!0-9a-f]*) fail '原部署中必须有且只有一个正在运行的指定服务；多副本部署请按说明手动操作' ;; esac
current_version=$(base_compose exec -T "$service" /app/sub2api --version 2>&1) || fail '无法读取现有程序版本；未修改容器'
version=$(printf '%s\n' "$current_version" | awk '/Sub2API / { for (i=1;i<NF;i++) if ($i=="Sub2API") { print $(i+1); exit } }')
[ "$version" = '0.2.15' ] || fail '本安装包仅适用于当前运行版本 0.2.15；未修改容器'
current_commit=$(printf '%s\n' "$current_version" | awk '/Sub2API / { for (i=1;i<=NF;i++) if ($i=="Sub2API") { if (i+3<=NF && $(i+2)=="(commit:") { commit=$(i+3); sub(/,$/,"",commit); print commit } exit } }')
[ "$current_commit" != 'f2669c8-gpt-monitor-ui-v3' ] || fail '当前程序已包含此管理页版本，无需重复安装'
[ "$current_commit" = 'f2669c8cf62555cd92389b3f55920e9e6e7c6ff2' ] || fail '当前构建基线不符：仅接受原版 0.2.15、完整 commit f2669c8cf62555cd92389b3f55920e9e6e7c6ff2；v1/v2 请先使用旧包 rollback.sh 恢复该原版后再安装；未修改容器'
image_id=$(docker inspect --format '{{.Image}}' "$container_id") || fail '读取当前镜像失败'
case "$image_id" in sha256:*) ;; *) fail '无法确认当前容器的镜像 ID' ;; esac
platform=$(docker image inspect --format '{{.Os}}/{{.Architecture}}' "$image_id") || fail '读取当前镜像架构失败'
case "$platform" in
  linux/amd64) binary="$bundle_dir/bin/linux-amd64/sub2api" ;;
  linux/arm64) binary="$bundle_dir/bin/linux-arm64/sub2api" ;;
  *) fail '仅支持 Linux amd64 和 arm64 镜像；未修改容器' ;;
esac
[ -x "$binary" ] || fail '程序缺少执行权限；请用 tar 在 Linux 上重新解压安装包'

# Quote YAML and escape Compose interpolation in the absolute bind-mount path.
yaml_binary=$(printf '%s' "$binary" | sed "s/'/''/g" | sed 's/\$/$$/g')
yaml_image=$(printf '%s' "$image_id" | sed "s/'/''/g")
(
  umask 077
  set -C
  cat > "$override_file" <<EOF
# Generated by gpt-monitor-patch/apply.sh. Keep the package directory in place.
services:
  '$service':
    image: '$yaml_image'
    pull_policy: never
    volumes:
      - type: bind
        source: '$yaml_binary'
        target: /app/sub2api
        read_only: true
        bind:
          create_host_path: false
EOF
) || fail '创建覆盖配置失败；未修改容器'

docker compose -f "$compose_file" -f "$override_file" config --quiet || fail 'Compose 配置检查失败；保留覆盖文件供检查，未重建容器'
docker compose -f "$compose_file" -f "$override_file" up -d --no-deps --force-recreate --pull never --no-build "$service" || fail '服务重建失败；请执行安装包内 rollback.sh 回滚'

attempt=0
verified=false
while [ "$attempt" -lt 15 ]; do
  attempt=$((attempt + 1))
  installed_version=$(docker compose -f "$compose_file" -f "$override_file" exec -T "$service" /app/sub2api --version 2>&1) || installed_version=''
  case "$installed_version" in
    *'Sub2API 0.2.15 (commit: f2669c8-gpt-monitor-ui-v3,'*) verified=true; break ;;
  esac
  sleep 2
done
[ "$verified" = true ] || fail '服务已重建，但未确认新程序版本；请查看容器日志或执行 rollback.sh'
printf '\n安装完成。刷新后台，打开「GPT 账号巡检」或 /admin/gpt-account-monitor，保存并启用检查。\n'
printf '后续启动须同时传入原 Compose 文件和 docker-compose.gpt-monitor.yml；请保留 gpt-monitor-patch 目录。\n'
