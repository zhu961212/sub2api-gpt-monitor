#!/bin/sh
# Remove only the monitor binary and retain the verified official 0.2.16 image.
set -eu
set -f

fail() { printf '回滚失败：%s\n' "$*" >&2; exit 1; }
[ "$#" -le 2 ] || fail '用法：sh gpt-monitor-patch-0.2.16/rollback.sh docker-compose.yml [sub2api]'
compose_file=docker-compose.yml
service=sub2api
if [ "$#" -ge 1 ]; then compose_file=$1; fi
if [ "$#" -ge 2 ]; then service=$2; fi
case "$service" in ''|*[!a-zA-Z0-9_.-]*) fail '服务名无效' ;; esac
[ -f "$compose_file" ] || fail '找不到原 Compose 文件；请在原部署目录执行'
compose_dir=$(CDPATH= cd -- "$(dirname -- "$compose_file")" && pwd -P)
[ "$(pwd -P)" = "$compose_dir" ] || fail '请先进入原 Compose 文件所在目录'
compose_file="$compose_dir/$(basename -- "$compose_file")"
rollback_file="$compose_dir/docker-compose.gpt-monitor.rollback-0.2.16.yml"
[ -f "$rollback_file" ] && [ ! -L "$rollback_file" ] || fail '缺少安装时生成的官方 0.2.16 镜像记录；不能仅使用可能仍指定 0.2.15 的原 Compose 文件回滚'
image_id=$(sed -n "s/^    image: '\(sha256:[0-9a-f]*\)'$/\1/p" "$rollback_file")
image_hash=${image_id#sha256:}
[ "$image_id" != "$image_hash" ] && [ "${#image_hash}" -eq 64 ] || fail '官方 0.2.16 镜像记录格式不符；未修改容器'
case "$image_hash" in *[!0-9a-f]*) fail '官方 0.2.16 镜像记录格式不符；未修改容器' ;; esac
# Accept only the exact image-only file produced by apply.sh for this service.
# This excludes accidental use of an old monitor overlay or another service.
cat <<EOF | cmp -s - "$rollback_file" || fail '官方 0.2.16 镜像记录已被修改或服务名不符；未修改容器'
# Official Sub2API 0.2.16, commit 01842576b3d5c1e2545b5a99ad555d36e28ed306.
# Generated by gpt-monitor-patch-0.2.16/apply.sh. Keep for rollback.
services:
  '$service':
    image: '$image_id'
    pull_policy: never
EOF
command -v docker >/dev/null 2>&1 || fail '找不到 docker 命令'
docker compose version >/dev/null 2>&1 || fail '需要 Docker Compose v2'
docker image inspect "$image_id" >/dev/null 2>&1 || fail '安装时记录的官方 0.2.16 镜像已不在本机；请按安装说明恢复该版本后再回滚'
official_compose() { docker compose -f "$compose_file" -f "$rollback_file" "$@"; }
official_compose config --quiet || fail '官方 0.2.16 Compose 配置检查失败'
official_compose up -d --no-deps --force-recreate --pull never --no-build "$service" || fail '服务重建失败，请查看 Compose 配置和容器日志'

attempt=0
verified=false
while [ "$attempt" -lt 15 ]; do
  attempt=$((attempt + 1))
  current_version=$(official_compose exec -T "$service" /app/sub2api --version 2>&1) || current_version=''
  case "$current_version" in
    *'Sub2API 0.2.16 (commit: 01842576b3d5c1e2545b5a99ad555d36e28ed306,'*) verified=true; break ;;
  esac
  sleep 2
done
[ "$verified" = true ] || fail '服务已重建，但未确认官方 0.2.16 版本；请查看容器日志，不要使用旧版程序回滚数据库'
printf '\n已移除巡检程序挂载，恢复官方 Sub2API 0.2.16。未执行 down，也未删除数据卷。\n'
printf '后续启动须使用原 Compose 文件和 docker-compose.gpt-monitor.rollback-0.2.16.yml，不再加载 docker-compose.gpt-monitor.yml。\n'
printf '此前检查修改的账号调度开关不会自动还原，请按需在账号管理中调整。\n'
